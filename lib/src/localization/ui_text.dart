import 'package:flutter/widgets.dart';

class UiText extends StatelessWidget {
  const UiText(
    this.data, {
    super.key,
    this.style,
    this.maxLines,
    this.overflow,
    this.textAlign,
    this.softWrap,
  });
  final String data;
  final TextStyle? style;
  final int? maxLines;
  final TextOverflow? overflow;
  final TextAlign? textAlign;
  final bool? softWrap;

  @override
  Widget build(BuildContext context) => Text(
    uiText(context, data),
    style: style,
    maxLines: maxLines,
    overflow: overflow,
    textAlign: textAlign,
    softWrap: softWrap,
  );
}

/// Translates app-owned legacy labels at the display boundary. Stored values,
/// filter identities and game-provided names stay in their original form.
String uiText(BuildContext context, String source) => uiTextForLocale(
  Localizations.maybeLocaleOf(context) ?? const Locale('zh'),
  source,
);

String uiTextForLocale(Locale locale, String source) {
  final japanese = locale.languageCode == 'ja';
  final traditional =
      locale.languageCode == 'zh' &&
      (locale.scriptCode == 'Hant' ||
          const ['TW', 'HK', 'MO'].contains(locale.countryCode));
  if (!japanese && !traditional) return source;
  final entry = uiTextTranslations[source];
  if (entry != null) return japanese ? entry.$2 : entry.$1;
  for (final template in _templates) {
    final match = template.$1.firstMatch(source);
    if (match == null) continue;
    return (japanese ? template.$3 : template.$2).replaceAllMapped(
      RegExp(r'\{(\d+)\}'),
      (slot) => uiTextForLocale(locale, match.group(int.parse(slot[1]!))!),
    );
  }
  return source;
}

final _templates = <(RegExp, String, String)>[
  (RegExp(r'^共 (\d+) 条$'), '共 {1} 條', '全 {1} 件'),
  (RegExp(r'^筛选(.+)记录$'), '篩選{1}記錄', '{1}記録の絞り込み'),
  (RegExp(r'^路线 (.+)$'), '路線 {1}', 'ルート {1}'),
  (RegExp(r'^改修消耗（(.+)）$'), '改修消耗（{1}）', '改修消費（{1}）'),
  (RegExp(r'^缺少 (\d+) 艘$'), '缺少 {1} 艘', '{1}隻不足'),
  (RegExp(r'^家具箱\((.+)\)$'), '家具箱（{1}）', '家具箱（{1}）'),
  (RegExp(r'^道具 (\d+)$'), '道具 {1}', 'アイテム {1}'),
];

